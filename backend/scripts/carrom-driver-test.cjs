const assert = require('node:assert/strict');
const { carromDriver } = require('../dist/games/carrom.js');
const ctx = {sessionId:'carrom-test',roomId:null,nowMs:Date.now(),rules:{turnTimeoutSeconds:90},players:[{userId:'a',position:0},{userId:'b',position:1}]};
let state=carromDriver.initialState(ctx);
assert.equal(state.coins.length,19);
assert.equal(state.coins.filter(c=>c.kind==='coin').length,18);
assert.equal(state.coins.filter(c=>c.kind==='queen').length,1);
assert.equal(state.turnPosition,0);
const bad=carromDriver.applyAction(state,ctx,'a',{type:'SHOT',payload:{angle:0,power:2}});
assert.equal(bad.ok,false);assert.equal(bad.code,'bad_shot');
const turn=carromDriver.applyAction(state,ctx,'b',{type:'SHOT',payload:{angle:0,power:.5}});
assert.equal(turn.ok,false);assert.equal(turn.code,'out_of_turn');
const malformed=carromDriver.applyAction(state,ctx,'a',{type:'MOVE',payload:{}});
assert.equal(malformed.ok,false);assert.equal(malformed.code,'unknown_action');
const repeat=carromDriver.applyAction(state,ctx,'a',{type:'SHOT',payload:{angle:90,power:.65,strikerX:500}});
const shot=carromDriver.applyAction(state,ctx,'a',{type:'SHOT',payload:{angle:90,power:.65,strikerX:500}});
assert.equal(shot.ok,true);
assert.equal(repeat.ok,true);
assert.deepEqual(repeat.state.coins,shot.state.coins,'identical server inputs must produce deterministic physics');
state=shot.state;
assert.equal(state.shotCount,1);
assert.equal(state.coins.length,19);
assert.ok(state.coins.every(c=>Number.isFinite(c.x)&&Number.isFinite(c.y)));
assert.ok(state.coins.every(c=>Number.isFinite(c.vx)&&Number.isFinite(c.vy)));
assert.equal(carromDriver.turnOwner(state,ctx)?.userId,state.turnPosition===0?'a':'b');
console.log('PASS  carrom: authoritative rack, input bounds, turn enforcement, deterministic bounded shot simulation and finite state');
